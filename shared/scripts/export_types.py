"""Generate shared/types/hearth.ts from JSON Schema without a Node dependency.

Supports the subset emitted by the shared models. Unknown structural keywords
fail loudly so future contract changes cannot silently produce incorrect types.
"""
import json
from pathlib import Path

SHARED = Path(__file__).resolve().parents[1]
ANNOTATIONS = {"title", "description", "default", "examples", "format", "discriminator",
               "minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum", "minLength",
               "maxLength", "minItems", "maxItems", "pattern", "deprecated", "readOnly", "writeOnly"}
STRUCTURAL = {"$ref", "anyOf", "oneOf", "enum", "const", "type", "items", "properties",
              "required", "additionalProperties"}


def ts_type(schema) -> str:
    if schema is True or schema == {}:
        return "unknown"
    if schema is False:
        return "never"
    unknown = set(schema) - ANNOTATIONS - STRUCTURAL
    if unknown:
        raise ValueError(f"Unsupported JSON Schema keywords: {sorted(unknown)}")
    if "$ref" in schema:
        prefix = "#/$defs/"
        if not schema["$ref"].startswith(prefix):
            raise ValueError("Only local definition references are supported")
        return schema["$ref"][len(prefix):]
    for union in ("anyOf", "oneOf"):
        if union in schema:
            return " | ".join(ts_type(s) for s in schema[union])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    kind = schema.get("type")
    if kind in {"string", "boolean", "null"}:
        return kind
    if kind in {"number", "integer"}:
        return "number"
    if kind == "array":
        return f"Array<{ts_type(schema['items'])}>"
    if kind == "object":
        properties = schema.get("properties", {})
        extra = schema.get("additionalProperties", True)
        if not properties:
            return f"Record<string, {ts_type(extra)}>"
        required = set(schema.get("required", []))
        fields = [f"  {json.dumps(name)}{'' if name in required else '?'}: {ts_type(value)};"
                  for name, value in properties.items()]
        if extra is not False:
            fields.append(f"  [key: string]: {ts_type(extra)};")
        return "{\n" + "\n".join(fields) + "\n}"
    raise ValueError(f"Unsupported schema: {schema}")


def render(bundle: dict) -> str:
    header = "// Generated by shared/scripts/export_types.py. DO NOT EDIT.\n"
    header += "// Server output types: defaulted fields are serialized; timestamps are ISO strings.\n\n"
    return header + "\n\n".join(f"export type {name} = {ts_type(schema)};"
                               for name, schema in sorted(bundle["$defs"].items())) + "\n"


def main():
    bundle = json.loads((SHARED / "schema/hearth.schema.json").read_text(encoding="utf-8"))
    output = SHARED / "types/hearth.ts"
    output.parent.mkdir(exist_ok=True)
    output.write_text(render(bundle), encoding="utf-8")
    print(f"wrote {output}")


if __name__ == "__main__":
    main()
